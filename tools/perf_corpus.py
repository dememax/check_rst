# Deterministic generated Sphinx corpus for performance measurements — check_rst project
"""Create the project/target-size matrix used by the performance recorder."""

from __future__ import annotations

import dataclasses
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path


@dataclasses.dataclass(frozen=True, slots=True)
class CorpusSize:
    """The independent scale dimensions of one generated project."""

    unrelated_documents: int
    large_page_sections: int
    fragment_includers: int = 3

    def __post_init__(self) -> None:
        if self.unrelated_documents < 0:
            raise ValueError("unrelated_documents must be non-negative")
        if self.large_page_sections < 1:
            raise ValueError("large_page_sections must be positive")
        if self.fragment_includers < 2:
            raise ValueError("fragment_includers must be at least two")


@dataclasses.dataclass(frozen=True, slots=True)
class GeneratedProject:
    """Paths and stable query titles for one generated Sphinx project."""

    root: Path
    small_target: Path
    large_target: Path
    size: CorpusSize
    small_title: str = "Small target"
    large_title: str = "Large target"


def _title(text: str, adornment: str) -> str:
    line = adornment * (len(text) + 2)
    return f"{line}\n{text}\n{line}\n\n"


def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")


def _large_page(section_count: int) -> str:
    parts = [_title("Large target", "#"), "A generated page with many sections.\n\n"]
    for number in range(1, section_count + 1):
        title = f"Large section {number:04d}"
        parts.extend(
            (
                _title(title, "*"),
                f"Generated paragraph {number:04d} keeps page size independent of project size.\n\n",
            )
        )
    return "".join(parts)


def generate_project(destination: Path, size: CorpusSize) -> GeneratedProject:
    """Generate a fresh project whose bytes depend only on *size*."""
    destination.mkdir(parents=True, exist_ok=False)
    _write(
        destination / "conf.py",
        '# Generated by check_rst; contains no external corpus text.\nproject = "check_rst performance corpus"\n'
        'extensions = []\nexclude_patterns = ["_build"]\n',
    )

    small_target = destination / "small.rst"
    large_target = destination / "large.rst"
    _write(small_target, _title("Small target", "#") + "A generated small target page.\n")
    _write(large_target, _large_page(size.large_page_sections))
    _write(
        destination / "fragment.rst",
        _title("Shared fragment", "*") + "Generated content included from several documents.\n",
    )

    toctree_entries = ["small", "large"]
    for number in range(1, size.fragment_includers + 1):
        stem = f"includer-{number:02d}"
        toctree_entries.append(stem)
        _write(
            destination / f"{stem}.rst",
            _title(f"Fragment includer {number:02d}", "#") + ".. include:: fragment.rst\n",
        )

    for number in range(1, size.unrelated_documents + 1):
        stem = f"unrelated-{number:04d}"
        toctree_entries.append(stem)
        _write(
            destination / f"{stem}.rst",
            _title(f"Unrelated document {number:04d}", "#") + f"Generated unrelated project content {number:04d}.\n",
        )

    entries = "".join(f"   {entry}\n" for entry in toctree_entries)
    _write(
        destination / "index.rst",
        _title("Performance corpus", "#") + ".. toctree::\n   :maxdepth: 2\n\n" + entries,
    )
    return GeneratedProject(root=destination, small_target=small_target, large_target=large_target, size=size)
